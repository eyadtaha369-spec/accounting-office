const DOTS = "....................";

/** قيمة إعداد نصي (العربية) */
export const settingText = (rows: Row[] | undefined, id: string) => (rows ?? []).find((r) => r.id === id)?.value_ar ?? "";

export function poaTemplateOf(rows: Row[] | undefined, kind: PoaKind) {
  return settingText(rows, POA_KEYS[kind]).trim() || (kind === "client" ? DEFAULT_CLIENT_POA : DEFAULT_ACCOUNTANT_POA);
}

const CLIENT_TYPE_AR: Record<string, string> = {
  individual: "بصفتي الشخصية",
  sole_proprietorship: "صاحب المنشأة الفردية",
  llc: "الممثل القانوني للشركة",
  joint_stock: "الممثل القانوني للشركة",
  other: "الممثل القانوني",
};

/** استبدال المتغيرات — أي قيمة غير معروفة تتحول لنقاط تُستكمل يدوياً */
export function fillPoa(
  text: string,
  opts: { settings?: Row[]; client?: Row | null; accountant?: { name?: string; nid?: string }; keepUnknown?: boolean } = {}
) {
  const c = opts.client ?? {};
  const company = c.company_name ? `${CLIENT_TYPE_AR[c.client_type] ?? "الممثل القانوني"} — ${c.company_name}` : CLIENT_TYPE_AR[c.client_type] ?? "";
  const values: Record<string, string> = {
    "{اسم_العميل}": c.full_name,
    "{الرقم_القومي}": c.national_id,
    "{العنوان}": c.address,
    "{صفة_العميل}": company,
    "{اسم_الشركة}": c.company_name,
    "{رقم_التسجيل_الضريبي}": c.tax_registration_number,
    "{المأمورية}": c.tax_office,
    "{اسم_المكتب}": settingText(opts.settings, POA_KEYS.officeName) || DEFAULT_OFFICE_NAME,
    "{رقم_القيد}": settingText(opts.settings, POA_KEYS.regNo),
    "{اسم_المحاسب}": opts.accountant?.name ?? "",
    "{الرقم_القومي_للمحاسب}": opts.accountant?.nid ?? "",
    "{التاريخ}": "..../..../........",
  };
  // نقبل المسافة بدل الشرطة السفلية، مثل: {رقم القيد}
  return text.replace(/\{([^{}\n]{1,40})\}/g, (m, inner: string) => {
    const key = `{${inner.trim().replace(/\s+/g, "_")}}`;
    if (!(key in values)) return m;
    const v = (values[key] ?? "").trim();
    return v || (opts.keepUnknown ? key : DOTS);
  });
}
